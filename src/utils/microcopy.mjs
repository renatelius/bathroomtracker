export const SCENARIOS = Object.keys(MSG);

/** Случайный элемент массива (допустим и непустой массив из 1 элемента). */
export function pickMessage(list) {
  if (!Array.isArray(list) || list.length === 0) return '';
  return list[Math.floor(Math.random() * list.length)];
}

/** Подставляет {value} в строку, если он есть. */
export function fillMessage(template, value) {
  return typeof template === 'string'
    ? template.replace(/\{value\}/g, value == null ? '' : String(value))
    : '';
}

/**
 * @param {'highCalories'|'lowWater'|'highStress'|'success'|'emptyField'} scenario
 * @param {string|number} [value] - число/значение для подстановки в {value}
 * @returns {string} случайная фраза сценария (пустая строка для незнакомого сценария)
 */
export function getMicrocopy(scenario, value) {
  return fillMessage(pickMessage(MSG[scenario] || null), value);
}

